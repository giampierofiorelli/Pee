"""D-1 constructed cases (REPORT.md §1.3), fixed before any run.

Each case has:
- one or more documents (holder, Markdown);
- the **correct** proposition units a careful reader would write (annotation-guide schema, T-1 fields where they
  apply), used to bypass the reader in S4–S6. ``doc`` says which document a unit belongs to (default 0);
- the expected translation (S3), as a few fields per expected claim;
- questions in A-1's format, with the expected answer and the support level actually known.

Domains: ecology, medicine, chemistry, materials, epidemiology, geology. None was used to design the reader.
"""


def unit(i, subject, relation, obj=None, polarity="affirmed", conditions=(), attitude="asserted",
         evidence="synthesis", kind="classification", value=None, **extra):
    u = {"type": "proposition", "id": i, "content_kind": kind, "relation": relation, "subject": subject,
         "object": obj, "value": value, "polarity": polarity, "modality": extra.pop("modality", "actual"),
         "generality": "generic", "conditions": [{"concept": c, "value": v} for c, v in conditions],
         "document_attitude": attitude, "evidence_kind": evidence, "attributed_to": extra.pop("attributed_to", []),
         "depends_on": [], "explains": [], "qualifies": None,
         "record": {"text": "", "locator": f"case {i}", "section": []}}
    u.update(extra)
    return u


